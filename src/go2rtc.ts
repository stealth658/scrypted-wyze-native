import { ChildProcess, spawn } from 'child_process';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';

/**
 * Pinned go2rtc release. Native Wyze support arrived in v1.9.14.
 * The checksums make sure the downloaded binary is exactly the official release.
 */
export const GO2RTC_VERSION = '1.9.15';
export const GO2RTC_SHA256: Record<string, string> = {
    amd64: '20b46c6910734cb05ecefb234066f36868ff19b42ba1418a7a32e13a3e035712',
    arm64: 'af416f22b21a24ab83b8d78642190b4932ae695b4e386853f11d1b0319781763',
};

export function go2rtcArch(arch = process.arch): string | undefined {
    if (arch === 'x64')
        return 'amd64';
    if (arch === 'arm64')
        return 'arm64';
    return undefined;
}

export interface Go2rtcOptions {
    filesDir: string;
    rtspPort: number;
    apiPort: number;
    logLevel: string;
    binaryOverride?: string;
}

function yamlString(s: string) {
    // JSON string syntax is valid YAML double-quoted syntax.
    return JSON.stringify(s);
}

export function buildConfig(opts: Go2rtcOptions, streams: Record<string, string>): string {
    const lines = [
        '# generated by scrypted-wyze-native, do not edit',
        'api:',
        `  listen: ${yamlString(`127.0.0.1:${opts.apiPort}`)}`,
        'rtsp:',
        `  listen: ${yamlString(`127.0.0.1:${opts.rtspPort}`)}`,
        // only Scrypted talks to go2rtc, over localhost RTSP. turn off everything else.
        'webrtc:',
        '  listen: ""',
        'srtp:',
        '  listen: ""',
        'rtmp:',
        '  listen: ""',
        'log:',
        `  level: ${yamlString(opts.logLevel || 'info')}`,
        'streams:',
    ];
    const names = Object.keys(streams);
    if (!names.length)
        lines[lines.length - 1] = 'streams: {}';
    for (const name of names)
        lines.push(`  ${yamlString(name)}: ${yamlString(streams[name])}`);
    return lines.join('\n') + '\n';
}

export class Go2rtc {
    private child?: ChildProcess;
    private stopping = false;
    private restartTimer?: NodeJS.Timeout;
    private streams: Record<string, string> = {};
    status = 'Not started';

    constructor(public opts: Go2rtcOptions, public console: Console) {
        fs.mkdirSync(opts.filesDir, { recursive: true });
    }

    get configPath() {
        return path.join(this.opts.filesDir, 'go2rtc.yaml');
    }

    get pidPath() {
        return path.join(this.opts.filesDir, 'go2rtc.pid');
    }

    rtspUrl(stream: string) {
        return `rtsp://127.0.0.1:${this.opts.rtspPort}/${encodeURIComponent(stream)}`;
    }

    async ensureBinary(): Promise<string> {
        if (this.opts.binaryOverride) {
            if (!fs.existsSync(this.opts.binaryOverride))
                throw new Error(`go2rtc binary override not found: ${this.opts.binaryOverride}`);
            return this.opts.binaryOverride;
        }
        const arch = go2rtcArch();
        if (!arch)
            throw new Error(`no go2rtc build is pinned for ${process.arch}. Set a go2rtc binary path in settings.`);
        const binPath = path.join(this.opts.filesDir, `go2rtc-${GO2RTC_VERSION}-linux-${arch}`);
        if (fs.existsSync(binPath))
            return binPath;

        const url = `https://github.com/AlexxIT/go2rtc/releases/download/v${GO2RTC_VERSION}/go2rtc_linux_${arch}`;
        this.console.log('downloading go2rtc', url);
        const res = await fetch(url);
        if (!res.ok)
            throw new Error(`go2rtc download failed: HTTP ${res.status}`);
        const data = Buffer.from(await res.arrayBuffer());
        const sha = crypto.createHash('sha256').update(data).digest('hex');
        if (sha !== GO2RTC_SHA256[arch])
            throw new Error(`go2rtc download checksum mismatch (got ${sha}). Not running it.`);
        const tmp = binPath + '.tmp';
        fs.writeFileSync(tmp, data, { mode: 0o755 });
        fs.renameSync(tmp, binPath);
        this.console.log('go2rtc downloaded and verified', binPath);
        return binPath;
    }

    /**
     * A previous plugin instance may have left go2rtc running and holding the ports.
     * Only kill it if it's our go2rtc, judged by its command line.
     */
    private killStale() {
        try {
            const pid = parseInt(fs.readFileSync(this.pidPath, 'utf8'));
            if (!pid)
                return;
            const cmdline = fs.readFileSync(`/proc/${pid}/cmdline`, 'utf8');
            if (cmdline.includes(this.configPath)) {
                this.console.log('stopping leftover go2rtc', pid);
                process.kill(pid, 'SIGKILL');
            }
        }
        catch (e) {
        }
    }

    setStreams(streams: Record<string, string>) {
        const changed = JSON.stringify(streams) !== JSON.stringify(this.streams);
        this.streams = streams;
        return changed;
    }

    async start() {
        this.stopping = false;
        clearTimeout(this.restartTimer);
        const bin = await this.ensureBinary();
        fs.writeFileSync(this.configPath, buildConfig(this.opts, this.streams), { mode: 0o600 });
        // stop our own instance first (marked as intentional), then any leftover from a previous plugin process.
        if (this.child)
            await this.stop();
        this.killStale();
        this.stopping = false;

        const child = spawn(bin, ['-config', this.configPath], { stdio: ['ignore', 'pipe', 'pipe'] });
        this.child = child;
        fs.writeFileSync(this.pidPath, String(child.pid));
        this.status = `Running (pid ${child.pid}, ${Object.keys(this.streams).length} streams)`;

        const log = (data: Buffer) => {
            for (const line of data.toString().split('\n')) {
                if (line.trim())
                    this.console.log('[go2rtc]', line.trim());
            }
        };
        child.stdout?.on('data', log);
        child.stderr?.on('data', log);
        this.verify(child).catch(() => { });
        child.on('exit', (code, signal) => {
            if (this.child === child)
                this.child = undefined;
            if (this.stopping)
                return;
            this.status = `Exited (${signal || code}), restarting`;
            this.console.error(`go2rtc exited (${signal || code}), restarting in 5s.`);
            this.restartTimer = setTimeout(() => this.start().catch(e => this.console.error('go2rtc restart failed', e)), 5000);
        });
    }

    /**
     * Confirm the go2rtc answering on our API port is ours, with our streams.
     * Catches a port already taken by another program (e.g. a separate wyze bridge).
     */
    private async verify(child: ChildProcess) {
        const expected = Object.keys(this.streams).sort();
        for (let i = 0; i < 10; i++) {
            await new Promise(r => setTimeout(r, 500));
            if (this.child !== child)
                return;
            try {
                const res = await fetch(`http://127.0.0.1:${this.opts.apiPort}/api/streams`);
                const names = Object.keys(await res.json()).sort();
                if (JSON.stringify(names) === JSON.stringify(expected)) {
                    this.status = `Running (pid ${child.pid}, ${expected.length} streams)`;
                    return;
                }
                this.status = `Port conflict: something else is answering on 127.0.0.1:${this.opts.apiPort}`;
                this.console.error(`${this.status}. Change the go2rtc ports in settings.`);
                return;
            }
            catch (e) {
            }
        }
        if (this.child === child) {
            this.status = 'Started but its API never answered; check the go2rtc log lines';
            this.console.error(this.status);
        }
    }

    async stop() {
        this.stopping = true;
        clearTimeout(this.restartTimer);
        const child = this.child;
        this.child = undefined;
        if (!child || child.exitCode !== null)
            return;
        await new Promise<void>(resolve => {
            const t = setTimeout(() => {
                child.kill('SIGKILL');
                resolve();
            }, 3000);
            child.once('exit', () => {
                clearTimeout(t);
                resolve();
            });
            child.kill('SIGTERM');
        });
        this.status = 'Stopped';
    }
}
